#!/usr/bin/env python3
"""Compile the public NRL English rules to the SSC's bytecode ROM.

Context alternatives are expanded without changing rule priority. # and :
compile to character classes and backtracking zero-or-more instructions.
The generated ROM is synchronous so Gowin can map it into block memory.
"""
import itertools
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'src/third_party/nrl_tts'
ALLOPHONES = ('PA1 PA2 PA3 PA4 PA5 OY AY EH KK3 PP JH NN1 IH TT2 RR1 AX '
              'MM TT1 DH1 IY EY DD1 UW1 AO AA YY2 AE HH1 BB1 TH UH UW2 '
              'AW DD2 GG3 VV GG1 SH ZH RR2 FF KK2 KK1 ZZ NG LL WW XR '
              'WH YY1 CH ER1 ER2 OW DH2 SS NN2 HH2 OR AR YR GG2 EL BB2').split()
CODES = {name: i for i, name in enumerate(ALLOPHONES)}
CLASSES = {'#': [128, 132], '^': [129], '.': [130], '+': [131], ':': [133]}
ALTERNATIVES = {'%': ['ER', 'E', 'ES', 'ED', 'ING', 'ELY'],
                '&': ['S', 'C', 'G', 'Z', 'X', 'J', 'CH', 'SH'],
                '@': ['T', 'S', 'R', 'D', 'L', 'Z', 'N', 'J', 'TH', 'CH', 'SH']}


def contexts(pattern, reverse=False):
    items = [ALTERNATIVES.get(c, [c]) for c in pattern]
    for parts in itertools.product(*items):
        expanded = ''.join(parts)
        if reverse:
            expanded = expanded[::-1]
        yield [b for c in expanded for b in CLASSES.get(c, [ord(c)])]


def compile_rules():
    source = json.loads((DATA / 'eng_to_ipa.json').read_text())
    mapping = json.loads((DATA / 'ipa_to_sp0256.json').read_text())
    phonemes = {}
    for name, rules in mapping.items():
        if name != 'PUNCT':
            phonemes[name] = rules[0].split('=')[1].strip('[]').split()
    phonemes.update({'< >': ['PA3'], '<,>': ['PA4'], '<.>': ['PA5'],
                     '<?>': ['PA5'], '<->': ['PA4']})
    rom = [0]  # address zero means no more rules
    groups = {}
    for group, lines in source.items():
        records = []
        for line in lines:
            left, body, right, output = re.fullmatch(r'(.*?)\[(.*?)\](.*?)=(.*)', line).groups()
            result = []
            for fragment in re.findall(r'/([^/]*)/', output):
                if fragment.strip():
                    for phoneme in ([fragment] if fragment.startswith('<') else fragment.split()):
                        result.extend(CODES[x] for x in phonemes[phoneme])
            assert body, line
            for pre, post in itertools.product(contexts(left, True), contexts(right)):
                assert sum(x in (132, 133) for x in pre) <= 4, line
                assert sum(x in (132, 133) for x in post) <= 4, line
                records.append(list(body.encode('ascii')) + [0] + pre + [0] + post + [0] + result + [255])
        groups[group] = len(rom)
        for i, record in enumerate(records):
            following = len(rom) + 2 + len(record) if i + 1 < len(records) else 0
            rom.extend([following & 255, following >> 8] + record)
    assert len(rom) <= 8192, len(rom)
    return rom, groups


def render():
    rom, groups = compile_rules()
    start = {ord(c): groups[c] for c in 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'}
    start.update({ord(c): groups['NUMBER'] for c in '0123456789'})
    start.update({ord(c): groups['PUNCT'] for c in " '-,.?"})
    text = '''// Generated by scripts/gen_ssc_tts.py from the public NRL rules.
// See src/third_party/nrl_tts/LICENSE and README.md for provenance.
module coco_ssc_tts_rom (
    input clk,input [12:0] address,output reg [7:0] data,
    input [7:0] letter,output reg [12:0] first_rule
);
    (* syn_romstyle = "block_rom" *) reg [7:0] rom [0:8191];
    initial begin
'''
    text += ''.join(f"        rom[{i}]=8'd{b};\n" for i, b in enumerate(rom))
    text += '''    end
    always @(posedge clk) data<=rom[address];
    always @* begin
        case(letter)
'''
    text += ''.join(f"            8'd{k}: first_rule=13'd{v};\n" for k, v in sorted(start.items()))
    text += '''            default: first_rule=0;
        endcase
    end
endmodule
'''
    return text, len(rom)


if __name__ == '__main__':
    text, size = render()
    (ROOT / 'src/audio/coco_ssc_tts_rom.v').write_text(text)
    print(f'SSC pronunciation ROM: {size}/8192 bytes')
